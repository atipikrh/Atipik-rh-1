        <p>La démarche peut aboutir à rester dans le même métier avec un autre cadrage, à évoluer dans l'entreprise, à se former, ou, parfois, à changer de voie. La décision reste la vôtre. Le consultant structure l'analyse, confronte les hypothèses au marché et sécurise la prochaine étape.</p>
