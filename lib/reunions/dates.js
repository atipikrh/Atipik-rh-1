/**
 * @param {{ date: string }[]} dates
 * @param {number} [limit]
 */
export function getUpcomingReunions(dates, limit = 3) {
  const today = new Date()
  today.setHours(0, 0, 0, 0)
  return dates.filter((reunion) => new Date(reunion.date) >= today).slice(0, limit)
}
